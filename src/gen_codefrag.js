function ensure(v, field, value) {
	// TODO: check this condition
	if (field === 'format' && value === 'path')
		value = 'blob';
	assert(typeof v === 'object');
	if (value === undefined)
		return;

	if (v[field] !== undefined) {
		if (v[field] !== value)
			abort(v, field, v[field], value);
		assert(v[field] === value);
	}

	v[field] = value;

	if (field === 'format' && !('decl' in v)) {
		v.decl = gen_decl(value, v.cvar);
	}
}

function obtain_plan(env, iface) {
	if (iface === undefined)
		iface = env.get_first_iface();

	var useful = true;
	while (useful) {
		useful = false;
		try {
			return derive_plan(env, iface).sequence;
		} catch (err) {
			if (err instanceof Env.CodeError) {
				var purged = env.purge_codefrag(err.locator);
				if (Object.keys(purged).length > 0)
					useful = true;
			} else
				nimpl(err);
		}
	}
}

class CpfCodefrag {
	#c_func_name; #env; #plan; #task; #vars; #next_var_id;
	#cm; #fwd_decls; #wrappers;

	constructor(env, task, plan) {
		this.#env = env;
		this.#task = task;
		this.#plan = plan;
		this.#c_func_name = env.register_c_func_name(this);
		this.#vars = {};
		this.#next_var_id = 0;
		this.#cm = this.#env.get_cm(task.cm);
		this.#fwd_decls = {};
		this.#wrappers = [];
	}

	repr() {
		return {
			env: this.#env,
			plan: this.#plan,
			c_func_name: this.#c_func_name,
			vars: this.#vars,
			fwd_decls: this.#fwd_decls,
			wrappers: this.#wrappers
		};
	}

	add_symbol_decl(c_func_name, code) {
		assert(c_func_name !== undefined);
		if (c_func_name in this.#fwd_decls)
			return;

		this.#fwd_decls[c_func_name] = gen_signature(code);
	}

	add_wrapper(symbol, code) {
		this.#wrappers.push(code);
	}

	as_input(arg) {
		var info = this.get_var(arg);

		if (info.kind === 'output') {
			switch (info.format) {
				case 'int32':
				case 'int64':
				case 'real32':
				case 'real64':
					return `*${info.cvar}`;
				case 'blob':
					return `*${info.cvar}, *${info.cvar}_size`;
				default:
					nimpl(info);
			}
		} else {
			switch (info.format) {
				case 'int32':
				case 'int64':
				case 'real32':
				case 'real64':
				case 'string':
					return info.cvar;
				case 'blob':
					return `${info.cvar}, ${info.cvar}_size`;
				default:
					nimpl(info);
			}
		}
	}

	as_output(arg) {
		var info = this.get_var(arg);

		if (info.kind === 'output') {
			switch (info.format) {
				case 'int32':
				case 'int64':
				case 'real32':
				case 'real64':
					return `${info.cvar}`;
				case 'blob':
					return `${info.cvar}, ${info.cvar}_size`;
				case 'string':
					return `${info.cvar}`;
				default:
					nimpl(info);
			}
		} else {
			switch (info.format) {
				case 'int32':
				case 'int64':
				case 'real32':
				case 'real64':
					return `&${info.cvar}`;
				case 'blob':
					return `&${info.cvar}, &${info.cvar}_size`;
				case 'string':
					return `&${info.cvar}`;
				default:
					nimpl(info, this.repr());
			}
		}
	}

	gen_c_module() {
		var signature = this.gen_my_signature();
		var locals = this.gen_locals();
		var invokes = this.gen_invokes();
		var wrappers = this.gen_wrappers();
		return `\
// Generated by src/gen_codefrag.js
#include <stddef.h>

// dependencies
${this.gen_deps()}

// wrappers
${wrappers}

${this.gen_my_signature()} {
	// local vars
	${locals}

	// invokes
	${invokes}
}
// End by src/gen_codefrag.js
`;
	}

	gen_deps() {
		var res = [];

		for (var id in this.#fwd_decls) {
			res.push(this.#fwd_decls[id] + ';');
		}

		return res.join("\n");
	}

	gen_invoke(code_locator, args) {
		// I should ask Env for symbol name for CPF codefrag
		// In this Env instance the dependency will be added
		var c_func_name = this.#env.get_symbol_for_code(code_locator);
		var code = this.#env.get_code(code_locator);
		if (c_func_name === code.c_func_name) {
			this.add_symbol_decl(c_func_name, code);
		} else {
			var wrapper_code = this.#env.get_code_by_symbol(c_func_name);
			this.add_wrapper(c_func_name, wrapper_code);
		}

		var cargs = [];

		assert(args.length === code.params.length);
		for (var i=0; i<args.length; i++) {
			if (env.is_locator(args[i])) {
				assert(code.params[i].kind === 'input');
				if (env.has_value(args[i]))
					cargs.push(env.get_c_value(args[i]));
				else
					abort("no value", args[i]);
			} else switch (code.params[i].kind) {
				case 'input':
					cargs.push(this.as_input(args[i]));
					break;
				case 'output':
					cargs.push(this.as_output(args[i]));
					break;
				default:
					nimpl(code.params[i]);
			}
		}

		return `${c_func_name}(${cargs.join(", ")});`;
	}

	dump_outs(op) {
		var res = [];
		var code = this.#env.get_code(op.code);
		res.push('//dump outs');
		for (var i=0; i<op.args.length; i++) {
			var p = code.params[i];
			var v = this.#vars[op.args[i]];
			if (p.kind === 'input')
				continue;
			//res.push(`// Dumping var ${op.args[i]} from ` +
				//`${v.cvar} of type ${p.type}`);
			res.push(`dump_${p.type}("${op.args[i]}", ` +
				`${this.as_input(op.args[i])});`);

		}
		res.push('');
		return res;
	}

	gen_invokes() {
		// loop through plan and invoke ops
		var invokes = [];
		for (var opid of this.#plan) {
			var op = this.#cm.ops[opid];
			invokes.push(this.gen_invoke(op.code, op.args));
			// TODO make run option: with dump
			//invokes = invokes.concat(this.dump_outs(op));
		}
		return invokes.join("\n\t");
	}

	gen_locals() {
		// loop through vars to ensure all data are gathered
		for (var opid of this.#plan) {
			var op = this.#cm.ops[opid];
			var code = this.#env.get_code(op.code);

			assert(code.params.length === op.args.length);

			for (var i=0; i<code.params.length; i++) {
				var arg = op.args[i];
				var param = code.params[i];
				this.get_var(arg);
				if (env.is_locator(arg))
					continue; // not a var
				switch (code.format) {
					case 'cpf':
						ensure(this.#vars[arg], 'format', param.format);
						break;
					case 'clif':
						if (!('format' in this.#vars[arg])) {
							ensure(this.#vars[arg], 'format',
								param.type);
						}
						break;
					default:
						nimpl(code, code.format, op.code);
				}
			}
		}

		var locals = [];
		for (var x in this.#vars) {
			var info = this.#vars[x];
			if (info.is_param || env.is_locator(x))
				continue;

			locals.push(`${info.decl};`);
		}
		return locals.join("\n\t");
	}

	gen_manifest() {
		return {
			type: 'codefrag',
			format: 'cpf',
			c_func_name: this.#c_func_name,
			params: this.#task.params
		}
	}

	gen_my_signature() {
		var params = this.get_params().map(param => {
			switch (param.kind) {
				case 'input':
					this.get_var(param.target, true);
					ensure(this.#vars[param.target], 'kind', 'input');
					ensure(this.#vars[param.target], 'format',
						param.format);
					return to_input_c_param(param,
						this.get_var(param.target, true).cvar);
				case 'output':
					this.get_var(param.source, true);
					ensure(this.#vars[param.source], 'kind', 'output');
					ensure(this.#vars[param.source], 'format',
						param.format);
					return to_output_c_param(param,
						this.get_var(param.source, true).cvar);
				default:
					nimpl(param);
			}
		});
		return `void ${this.get_c_func_name()}(${params.join(", ")})`;
	}

	gen_wrappers() {
		return this.#wrappers.map(code => code.listing).join("\n\n");
	}

	get_c_func_name() {
		return this.#c_func_name;
	}

	get_var(x, is_param) {
		if (!(x in this.#vars)) {
			this.#vars[x] = {
				cvar: `_v${this.#next_var_id++}`
			}
		}
		ensure(this.#vars[x], 'is_param', is_param);
		return this.#vars[x];
	}

	get_params() {
		return this.#task.params;
	}

	export() {
		return {
			listing: this.gen_c_module(),
			manifest: this.gen_manifest()
		};
	}
}

