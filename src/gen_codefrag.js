// Here we generate a CPF which implements plan and may invoke
// both CPFs and CLIFs
// then we generate a main which calls the CPF.
function gen_clif(env, iface, plan) {
	assert(iface.format === 'clif');

	// below we create complaint CPF iface and generate CPF code
	var cpf_iface = jclone(iface);
	cpf_iface.format = 'cpf';

	for (var param of cpf_iface.params) {
		switch (param.type) {
			case 'int32':
			case 'real64':
			case 'blob':
			case 'string':
				param.format = param.type;
				break;
			default:
				nimpl(param, iface, plan, cpf_iface);
		}
	}

	// generate CPF
	var cpf = gen_cpf(env, cpf_iface, plan);

	var { listing, manifest } = cpf.export();

	// Now generate a CLIF main which calls the CPF
	var clif_jaz = {
		cm: { main: { names: {}, ops: {
			main: {
				type: 'simple',
				code: 'local://code/main',
				args: []
			}
		} } },
		plan: {
			main: {
				iface: "local://iface/main",
				plan: ["main"],
				sequence: ["main"],
				score: 1
			}
		},
		iface: {
			main: {
				cm: "local://cm/main",
				format: 'clif',
				params: jclone(iface.params)
			}
		},
		code: {
			main: jclone(manifest)
		}
	};

	clif_jaz.code.main.listing = listing;

	for (var param of iface.params) {
		switch (param.kind) {
			case 'input':
				clif_jaz.cm.main.names[param.target] = {};
				clif_jaz.cm.main.ops.main.args.push(param.target);
				break;
			case 'output':
				clif_jaz.cm.main.names[param.source] = {};
				clif_jaz.cm.main.ops.main.args.push(param.source);
				break;
			default:
				nimpl(param)
		}
	}

	var clif_wrapper = gen_clif_c(JSON.stringify(clif_jaz));

	var res = jclone(clif_jaz.iface.main);
	res.listing = clif_wrapper;
	return res;
}

function obtain_program_old(env, plan, iface) {
	if (plan === null)
		nimpl(iface, plan);
	if (iface === undefined)
		iface = env.get_first_iface();

	var useful = true;
	while (useful) {
		useful = false;

		try {
			switch (iface.format) {
				case 'cpf':
					return gen_cpf(env, iface, plan).export();
				case 'clif':
					var manifest = gen_clif(env, iface, plan);
					return {
						manifest,
						listing: manifest.listing
					};
				default:
					nimpl(iface);
			}
		} catch (err) {
			nimpl(err);
		}
	}
}

function obtain_program(env, plan, iface) {
	if (plan === null)
		nimpl(iface, plan);
	if (iface === undefined)
		iface = env.get_first_iface();

	switch (iface.format) {
		case 'cpf':
			return gen_cpf(env, iface, plan).export();
		case 'clif':
			var manifest = gen_clif(env, iface, plan);
			return {
				manifest,
				listing: manifest.listing
			};
		case 'dclif':
			return gen_mpi_dclif(env, iface, plan);
		default:
			nimpl(iface);
	}
}

var env;
function gen_codefrag(jaz) {
	assert(arguments.length === 1);
	if (!('plan' in jaz))
		abort();
	env = new Env(JSON.parse(JSON.stringify(jaz)));

	var plan = env.get_sequence("plan1");
	var iface = env.get_iface("plan1");

	var { manifest, listing } = obtain_program(env, plan, iface);

	return { manifest, listing };
}

