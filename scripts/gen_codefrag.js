function obtain_program(env, plan, task) { // ???
	if (plan === null)
		nimpl(task, plan);
	if (task === undefined)
		task = env.get_first_task();

	var useful = true;
	while (useful) {
		useful = false;
		// var plan = obtain_plan(env, task);
		// if (plan === null)
		// 	nimpl(task, plan);

		try {
			switch (task.format) {
				case 'cpf':
					return gen_cpf(env, task, plan);
				default:
					nimpl(task);
			}
		} catch (err) {
			nimpl(err);
		}
	}
}

